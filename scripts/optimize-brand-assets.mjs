import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { brandAssets } from "../lib/brand.ts";

const root = resolve(import.meta.dirname, "..");
const output = resolve(root, "public", "brand");
await mkdir(output, { recursive: true });

for (const [name, asset] of Object.entries(brandAssets.header)) {
  const source = resolve(root, asset.source);
  const pipeline = sharp(source).extract(asset.crop).resize({ width: 640, withoutEnlargement: true });
  await pipeline.clone().avif({ quality: 58, effort: 5 }).toFile(resolve(output, `praiamar-${name}.avif`));
  await pipeline.clone().webp({ quality: 82, effort: 5 }).toFile(resolve(output, `praiamar-${name}.webp`));
  console.log(`praiamar-${name}: AVIF and WebP`);
}

// Loader art is inlined as data URIs in a CSS module: it paints with the first frame (CSS is render-blocking)
// without a network request and without adding weight to the JavaScript bundle.
const loader = brandAssets.loader;
const art = {};
for (const [name, crop] of Object.entries(loader.parts)) {
  const width = name === "wordmark" ? 400 : crop.width;
  const buffer = await sharp(resolve(root, loader.source)).extract(crop).resize({ width }).webp({ quality: 80, alphaQuality: 70, effort: 6 }).toBuffer();
  art[name] = `data:image/webp;base64,${buffer.toString("base64")}`;
  console.log(`loader ${name}: ${buffer.length} bytes`);
}
const css = Object.entries(art).map(([name, uri]) => `.${name} { background-image: url("${uri}"); }`).join("\n");
const header = "/* Generated by scripts/optimize-brand-assets.mjs — do not edit. */";
await writeFile(resolve(root, "components", "LoaderArt.generated.module.css"), `${header}\n${css}\n`);
